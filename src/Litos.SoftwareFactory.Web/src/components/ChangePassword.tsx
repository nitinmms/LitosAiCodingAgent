import { useState, type FormEvent } from 'react';
import { ApiError, type FactoryApi } from '../api/client';
import type { CurrentUser } from '../api/types';
import { ErrorNote, Mark } from './bits';

/** The host's rule (FactoryAuth: Password.RequiredLength). */
export const MIN_PASSWORD_LENGTH = 12;

/**
 * Changing one's own password. Required, it is the whole screen: an account whose password was
 * generated and shown once can do nothing else until it chooses its own
 * (SoftwareFactoryInstallation.md §4.4). Otherwise it is a panel the top bar opens.
 */
export function ChangePassword({
  api,
  required = false,
  onChanged,
  onCancel,
  onSignOut,
}: {
  api: FactoryApi;
  required?: boolean;
  onChanged: (user: CurrentUser) => void;
  onCancel?: () => void;
  onSignOut?: () => void;
}) {
  const [current, setCurrent] = useState('');
  const [next, setNext] = useState('');
  const [repeat, setRepeat] = useState('');
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    if (busy) return;
    if (next.length < MIN_PASSWORD_LENGTH) return setError(`The new password must be at least ${MIN_PASSWORD_LENGTH} characters.`);
    if (next !== repeat) return setError('The two new passwords are not the same.');

    setBusy(true);
    setError(null);
    try {
      onChanged(await api.changePassword(current, next));
    } catch (failure) {
      setError(failure instanceof ApiError ? failure.message : 'The password could not be changed.');
      setBusy(false);
    }
  };

  const form = (
    <form className="stack" onSubmit={submit} aria-label="Change password">
      <h2>{required ? 'Choose your own password' : 'Change password'}</h2>
      {required ? (
        <p className="small muted">
          The password you signed in with was generated by the installer and works only once. Choose one of your own, at
          least {MIN_PASSWORD_LENGTH} characters, before you go on.
        </p>
      ) : null}
      <div className="field">
        <label htmlFor="pw-current">{required ? 'The password you signed in with' : 'Current password'}</label>
        <input id="pw-current" type="password" value={current} onChange={(e) => setCurrent(e.target.value)} autoComplete="current-password" required />
      </div>
      <div className="field">
        <label htmlFor="pw-new">New password</label>
        <input id="pw-new" type="password" value={next} onChange={(e) => setNext(e.target.value)} autoComplete="new-password" required />
        <span className="hint">At least {MIN_PASSWORD_LENGTH} characters.</span>
      </div>
      <div className="field">
        <label htmlFor="pw-repeat">New password again</label>
        <input id="pw-repeat" type="password" value={repeat} onChange={(e) => setRepeat(e.target.value)} autoComplete="new-password" required />
      </div>
      <ErrorNote message={error} />
      <div className="btn-row">
        <button className="btn primary" type="submit" disabled={busy}>
          Save new password
        </button>
        {onCancel ? (
          <button className="btn" type="button" onClick={onCancel} disabled={busy}>
            Cancel
          </button>
        ) : null}
        {onSignOut ? (
          <button className="btn ghost" type="button" onClick={onSignOut} disabled={busy}>
            Sign out
          </button>
        ) : null}
      </div>
    </form>
  );

  return required ? (
    <div className="login">
      <section className="login-art">
        <div className="brand">
          <Mark /> Litos Software Factory
        </div>
      </section>
      <section className="login-form">{form}</section>
    </div>
  ) : (
    <div className="page">
      <section className="section">{form}</section>
    </div>
  );
}
